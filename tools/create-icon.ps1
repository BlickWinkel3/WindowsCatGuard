$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, WindowsBase

$visual = [System.Windows.Media.DrawingVisual]::new()
$drawing = $visual.RenderOpen()
$lavender = [System.Windows.Media.SolidColorBrush]::new([System.Windows.Media.ColorConverter]::ConvertFromString('#E8DFF3'))
$ink = [System.Windows.Media.SolidColorBrush]::new([System.Windows.Media.ColorConverter]::ConvertFromString('#242735'))
$drawing.DrawRoundedRectangle($lavender, $null, [System.Windows.Rect]::new(8, 8, 240, 240), 60, 60)
$drawing.DrawEllipse($ink, $null, [System.Windows.Point]::new(128, 158), 54, 43)
$drawing.DrawEllipse($ink, $null, [System.Windows.Point]::new(50, 100), 16, 23)
$drawing.DrawEllipse($ink, $null, [System.Windows.Point]::new(94, 64), 17, 25)
$drawing.DrawEllipse($ink, $null, [System.Windows.Point]::new(160, 64), 17, 25)
$drawing.DrawEllipse($ink, $null, [System.Windows.Point]::new(206, 100), 16, 23)
$drawing.Close()

$bitmap = [System.Windows.Media.Imaging.RenderTargetBitmap]::new(256, 256, 96, 96, [System.Windows.Media.PixelFormats]::Pbgra32)
$bitmap.Render($visual)
$encoder = [System.Windows.Media.Imaging.PngBitmapEncoder]::new()
$encoder.Frames.Add([System.Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
$pngStream = [System.IO.MemoryStream]::new()
$encoder.Save($pngStream)
$png = $pngStream.ToArray()
$pngStream.Dispose()

$output = [System.IO.MemoryStream]::new()
$writer = [System.IO.BinaryWriter]::new($output)
$writer.Write([uint16]0)
$writer.Write([uint16]1)
$writer.Write([uint16]1)
$writer.Write([byte]0) # 256 pixels
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([byte]0)
$writer.Write([uint16]1)
$writer.Write([uint16]32)
$writer.Write([uint32]$png.Length)
$writer.Write([uint32]22)
$writer.Write($png)
$writer.Flush()
[System.IO.File]::WriteAllBytes((Join-Path $PSScriptRoot '../assets/paw.ico'), $output.ToArray())
$writer.Dispose()
$output.Dispose()
